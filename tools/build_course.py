def entropy(p):
    return -sum(x * math.log2(x) for x in p if x)

def n(prompt, answer, explanation, tolerance=.001, variant=None):
    return dict(kind='number', prompt=prompt, answer=str(answer), explanation=explanation, options=[], tolerance=tolerance, variant=variant)

def m(prompt, options, correct, explanation):
    return dict(kind='choice', prompt=prompt, options=options, answer=str(correct), explanation=explanation)

def s(prompt, answer, explanation):
    return dict(kind='self', prompt=prompt, options=[], answer=answer, explanation=explanation)

